"""Safe ZIP export for code blocks explicitly requested by the operator."""
from __future__ import annotations

import io
import re
import uuid
import zipfile
from pathlib import Path
from .config import ROOT, EXPORTS_DIR

MAX_MARKDOWN_CHARS = 160_000
MAX_FILES = 24
MAX_FILE_CHARS = 80_000
MAX_TOTAL_CHARS = 500_000
ALLOWED_EXTENSIONS = {
    ".html", ".htm", ".css", ".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsx",
    ".py", ".json", ".md", ".txt", ".sql", ".java", ".cs", ".cpp", ".c",
    ".h", ".hpp", ".go", ".rs", ".php", ".rb", ".ps1", ".psm1", ".bat",
    ".cmd", ".sh", ".yaml", ".yml", ".xml", ".svg", ".toml", ".ini", ".env",
    ".example", ".vue", ".svelte", ".kt", ".swift", ".dart", ".jsx", ".tsx",
}
LANGUAGE_EXTENSION = {
    "html": ".html", "htm": ".html", "css": ".css", "javascript": ".js", "js": ".js",
    "typescript": ".ts", "ts": ".ts", "tsx": ".tsx", "jsx": ".jsx", "python": ".py", "py": ".py",
    "json": ".json", "sql": ".sql", "bash": ".sh", "sh": ".sh", "powershell": ".ps1",
    "ps1": ".ps1", "java": ".java", "csharp": ".cs", "c#": ".cs", "cpp": ".cpp", "go": ".go", "rust": ".rs",
    "markdown": ".md", "md": ".md", "xml": ".xml", "yaml": ".yaml", "yml": ".yaml", "text": ".txt", "txt": ".txt",
}
FENCE_RE = re.compile(r"```([^\n`]*)\n(.*?)```", re.DOTALL)


def _safe_filename(value: str, fallback: str) -> str:
    name = (value or "").strip().strip("`'\"* ")
    name = name.replace("\\", "/").split("/")[-1]
    name = re.sub(r"[^A-Za-z0-9._-]+", "_", name).strip("._")
    if not name or name in {".", ".."}:
        name = fallback
    suffix = Path(name).suffix.lower()
    if suffix not in ALLOWED_EXTENSIONS:
        name = Path(name).stem + fallback[fallback.rfind("."):] if "." not in name else name + fallback[fallback.rfind("."):]
    return name[:100]


def _infer_name(markdown: str, fence_start: int, language: str, index: int) -> str:
    before = markdown[max(0, fence_start - 180):fence_start]
    matches = re.findall(r"(?:\*\*|`)([A-Za-z0-9_. -]+\.[A-Za-z0-9]+)(?:\*\*|`)", before)
    if matches:
        candidate = matches[-1].strip()
        return _safe_filename(candidate, f"file-{index:02d}.txt")
    extension = LANGUAGE_EXTENSION.get(language.strip().lower(), ".txt")
    return f"file-{index:02d}{extension}"


def extract_code_files(markdown: str) -> list[dict[str, str]]:
    if not isinstance(markdown, str) or len(markdown) > MAX_MARKDOWN_CHARS:
        raise ValueError(f"Response must be text no longer than {MAX_MARKDOWN_CHARS} characters")
    matches = list(FENCE_RE.finditer(markdown))
    if not matches:
        raise ValueError("No complete fenced code blocks were found in the assistant response")
    if len(matches) > MAX_FILES:
        raise ValueError(f"Too many code blocks; maximum is {MAX_FILES}")
    results: list[dict[str, str]] = []
    used: set[str] = set()
    total = 0
    for index, match in enumerate(matches, 1):
        info = match.group(1).strip()
        language = info.split()[0] if info else "text"
        hinted = re.search(r"(?:file|filename)\s*=\s*[\"']?([^\s\"']+)", info, re.I)
        filename = _safe_filename(hinted.group(1), f"file-{index:02d}.txt") if hinted else _infer_name(markdown, match.start(), language, index)
        if filename in used:
            stem, suffix = Path(filename).stem, Path(filename).suffix
            n = 2
            while f"{stem}-{n}{suffix}" in used:
                n += 1
            filename = f"{stem}-{n}{suffix}"
        content = match.group(2)
        if len(content) > MAX_FILE_CHARS:
            raise ValueError(f"{filename} exceeds the per-file export limit")
        total += len(content)
        if total > MAX_TOTAL_CHARS:
            raise ValueError("The combined code export exceeds the size limit")
        used.add(filename)
        results.append({"path": filename, "content": content})
    return results


def build_code_export(markdown: str) -> tuple[bytes, str, list[str]]:
    files = extract_code_files(markdown)
    archive_id = uuid.uuid4().hex
    if EXPORTS_DIR.is_symlink():
        raise ValueError("The generated export directory cannot be a symbolic link")
    EXPORTS_DIR.mkdir(parents=True, exist_ok=True)
    root = EXPORTS_DIR.resolve(strict=True)
    root.relative_to(ROOT.resolve(strict=True))
    target = root / f"jarvis-code-{archive_id}.zip"
    if target.exists() or target.is_symlink():
        raise FileExistsError("Generated export identifier collision")
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        archive.writestr("README-GENERATED-BY-JARVIS.txt",
            "Generated by J.A.R.V.I.S.\n\nReview all generated code before running it. "
            "Generated files are inert until you choose to open or execute them.\n")
        for item in files:
            archive.writestr(item["path"], item["content"])
    payload = stream.getvalue()
    if target.is_symlink():
        raise ValueError("The export target cannot be a symbolic link")
    target.write_bytes(payload)
    return payload, target.name, [item["path"] for item in files]


def resolve_export_file(filename: str) -> Path:
    if not re.fullmatch(r"jarvis-code-[0-9a-f]{32}\.zip", filename or ""):
        raise ValueError("Invalid export identifier")
    base = EXPORTS_DIR.resolve(strict=True)
    target = (base / filename).resolve(strict=True)
    target.relative_to(base)
    if not target.is_file() or target.is_symlink():
        raise FileNotFoundError("Generated export not found")
    return target
